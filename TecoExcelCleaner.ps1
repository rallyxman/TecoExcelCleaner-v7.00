<#
.SYNOPSIS
    Cleans HTML and extracts only the first work note entry from Excel files generated by ServiceNow (incident/sc_task exports).

.DESCRIPTION
    This script provides a GUI to automate the cleansing of ServiceNow work notes.
    It removes all HTML tags, square brackets, and extracts only the first date-stamped
    entry from the 'Work notes' column, exporting the result to a new '_cleaned.xlsx' file.
    
    This is the high-speed, stable, single-threaded version.
    
.NOTES
    Version: 7.00
    Philosophy: Yata R&D / Modular Design & Versioning
    Dependencies: ImportExcel PowerShell Module
#>

# ==========================================================
# === 1. TOP-LEVEL CONFIGURATION AND LOGGING SETUP
# ==========================================================

$ScriptVersion = "7.00"
$DebugMode = $false 
$LogDir = "$env:USERPROFILE\Documents\TecoExcelCleanerLogs"
$DaysToKeep = 30

if (-not (Test-Path $LogDir)) { New-Item -ItemType Directory -Path $LogDir | Out-Null }

# === LOGGING ENGINE ===
function Write-Log {
    param(
        [Parameter(Mandatory=$true)][string]$Message, 
        [ValidateSet("INFO","WARN","ERROR","DEBUG")] [string]$Level = "INFO",
        [bool]$IsDebugMode = $false 
    )
    $LogFile = Join-Path $LogDir ("CleanerLog-" + (Get-Date -Format "yyyyMMdd") + ".txt")
    
    $timestamp = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
    $entry = "[$timestamp][$Level] $Message"
    Add-Content -Path $LogFile -Value $entry
}

Write-Log "=== Script Started (TecoExcelCleaner v$ScriptVersion) ===" -IsDebugMode $DebugMode

# ==========================================================
# === 2. CORE UTILITY FUNCTIONS
# ==========================================================

function Clean-Text($text) {
    if (-not $text) { return "" }
    $text = [System.Net.WebUtility]::HtmlDecode($text)
    $text = $text -replace '<[^>]*>', ''
    $text = $text -replace '\[[^\]]*\]', ''
    return ($text -replace '\s+', ' ').Trim()
}

function Extract-FirstWorkNote($fullText) {
    if (-not $fullText) { return "" }
    
    $pattern = '(?ms)(^\s*\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}.+?)(?=[
]+\s*\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} - [^(
]+ \(Work notes\)|\z)'
    
    if ($fullText -match $pattern) {
        return Clean-Text $Matches[1].Trim()
    }
    return Clean-Text $fullText
}

# ==========================================================
# === 3. DEPENDENCY CHECK AND FILE PROCESSING
# ==========================================================

function Check-Dependencies {
    param([Parameter(Mandatory=$true)][bool]$IsDebugMode)
    $RequiredModules = @('ImportExcel')
    
    foreach ($module in $RequiredModules) {
        if (-not (Get-Module -ListAvailable -Name $module)) {
            try { 
                Install-Module -Name $module -Scope CurrentUser -Force -AllowClobber -ErrorAction Stop 
            } catch {
                [System.Windows.Forms.MessageBox]::Show("Failed to install required module $module. Check your internet connection.", "Dependency Error", "OK", "Error"); exit
            }
        }
    }
    Import-Module ImportExcel -ErrorAction SilentlyContinue
}

function Process-File {
    param(
        [Parameter(Mandatory=$true)][System.IO.FileInfo]$file,
        [Parameter(Mandatory=$true)][System.Windows.Forms.Label]$statusLabel,
        [Parameter(Mandatory=$true)][System.Windows.Forms.FlowLayoutPanel]$progressPanel,
        [Parameter(Mandatory=$true)][System.Windows.Forms.Form]$form
    )
    
    $statusLabel.Text = "Processing $($file.Name)..."
    $form.Refresh()

    try {
        $data = Import-Excel -Path $file.FullName -ErrorAction Stop
        
        foreach ($row in $data) {
            $row.'Work notes' = Extract-FirstWorkNote $row.'Work notes'
        }

        $newName = [System.IO.Path]::Combine($file.DirectoryName, ($file.BaseName + "_cleaned.xlsx"))
        if (Test-Path $newName) { Remove-Item $newName -Force }
        
        $data | Export-Excel -Path $newName -WorksheetName "Cleaned" 
        
        $statusLabel.Text = "✅ Cleaned: $($file.Name)"
    } catch {
        Write-Log "Error processing $($file.FullName): $($_.Exception.Message)" "ERROR"
        $statusLabel.Text = "❌ Error processing $($file.Name). Check logs."
    }
}

