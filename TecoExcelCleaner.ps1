$easyButton.Add_Click({
    $progressPanel.Controls.Clear()
    $downloads = [Environment]::GetFolderPath('UserProfile') + "\Downloads"
    $today = (Get-Date).Date
    $incidentFile = Get-ChildItem $downloads -Filter "incident*.xlsx" | Where-Object { $_.LastWriteTime.Date -eq $today } | Sort-Object LastWriteTime -Descending | Select-Object -First 1
    $taskFile     = Get-ChildItem $downloads -Filter "sc_task*.xlsx"  | Where-Object { $_.LastWriteTime.Date -eq $today } | Sort-Object LastWriteTime -Descending | Select-Object -First 1
    $filesToProcess = @($incidentFile, $taskFile) | Where-Object { $_ -ne $null }

    if ($filesToProcess.Count -eq 0) { 
        [System.Windows.Forms.MessageBox]::Show("No incident or sc_task Excel files found in Downloads for today.", "Notice", "OK", "Information")
        return 
    }

    foreach ($file in $filesToProcess) {
        Process-File -file $file -statusLabel $statusLabel -progressPanel $progressPanel -form $form
    }
})

$selectFileButton.Add_Click({
    $progressPanel.Controls.Clear()
    $dialog = New-Object System.Windows.Forms.OpenFileDialog
    $dialog.Filter = "Excel Files (*.xlsx)|*.xlsx|All Files (*.*)|*.*"
    if ($dialog.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) { 
        $fileInfo = Get-Item $dialog.FileName -ErrorAction SilentlyContinue
        Process-File -file $fileInfo -statusLabel $statusLabel -progressPanel $progressPanel -form $form
    } else {
        $statusLabel.Text = "File selection cancelled."
    }
})

